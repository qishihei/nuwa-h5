MARKER = '## 人格化表达层（第一人称轶事）'

def build_section(name, items):
    lines = [
        '', '', MARKER, '',
        '当用户以「你当年…」「作为大师本人」「讲讲你的经历」或直接请求个人口吻时，',
        '切换到**第一人称**，用大师本人口吻作答，并自然地嵌入下面这些**有据可查**的轶事与经历。',
        '规则：只讲出自公认传记 / 著作 / 演讲、反复被印证的事实；记不清或存疑就说「这我记不真切」，绝不杜撰细节、年代、对话。',
        '目的：让对话从「用他的框架推理」升级为「像在与这位大师本人促膝长谈」，温度与可信度并存。',
        '',
        '### 可考轶事',
    ]
    for i, t in enumerate(items, 1):
        lines.append(f'{i}. {t}')
    return '\n'.join(lines) + '\n'

def process(name, all_mode=False):
    p = os.path.join(SKILLS, name, 'SKILL.md')
    if not os.path.exists(p):
        print('SKIP (no SKILL.md):', name); return
    txt = open(p, 'r', encoding='utf-8').read()
    if MARKER in txt:
        print('OK   (已含,跳过):', name); return
    items = ANECDOTES.get(name)
    if not items:
        if not all_mode:
            print('SKIP (样本未含):', name); return
        print('WARN (缺轶事数据,跳过):', name); return
    with open(p, 'a', encoding='utf-8') as f:
        f.write(build_section(name, items))
    print('ADD  :', name, f'(+{len(items)}条轶事)')

if __name__ == '__main__':
    all_mode = '--all' in sys.argv
    names = list(ANECDOTES.keys()) if not all_mode else \
        [d for d in os.listdir(SKILLS) if os.path.isdir(os.path.join(SKILLS, d))]
    for n in names:
        process(n, all_mode)
    print('\n完成。', '（样本模式）' if not all_mode else '（全量模式）')
